#!/usr/bin/env bash
# Port of start-campaign.ps1 + start-multiplayer.ps1: prepares the server folder, writes one
# dedicated.toml with two servers (campaign co-op and a multiplayer playlist) and runs them.
set -euo pipefail

SERVER_DIR="${SERVER_DIR:-/server}"
MCC_DIR="${MCC_DIR:-/mcc}"
VERSION_FILE="${VERSION_FILE:-/opt/reclaimer/VERSION}"

CONFIG_FILE="${CONFIG_FILE:-/etc/reclaimer/reclaimer.config.json}"   # ./config, shared with the PowerShell scripts

log() { echo "[entrypoint] $*"; }
die() { echo "[entrypoint] error: $*" >&2; exit 1; }
tstr() { jq -Rn --arg s "$1" '$s'; }   # TOML/JSON-safe quoted string
cfg() { jq -r "$1" "$CONFIG_FILE"; }
if [ ! -f "$CONFIG_FILE" ]; then
  DEFAULT_CONFIG=/usr/share/reclaimer/default.config.json
  [ -f "$DEFAULT_CONFIG" ] || die "$CONFIG_FILE not found and no built-in default"
  log "$CONFIG_FILE not found; using the built-in default settings"
  CONFIG_FILE="$DEFAULT_CONFIG"
fi

# Environment variables override the shared file; empty means "use the file".
CAMPAIGN_PORT="${CAMPAIGN_PORT:-$(cfg .campaign.port)}"
MULTIPLAYER_PORT="${MULTIPLAYER_PORT:-$(cfg .multiplayer.port)}"
CAMPAIGN_NAME="${CAMPAIGN_NAME:-$(cfg .campaign.name)}"
MULTIPLAYER_NAME="${MULTIPLAYER_NAME:-$(cfg .multiplayer.name)}"
MISSION="${MISSION:-$(cfg .campaign.default_mission)}"
VOTE_SECONDS="${VOTE_SECONDS:-$(cfg .multiplayer.vote_seconds)}"
RCON_ADDRESS="${RCON_ADDRESS:-0.0.0.0}"   # inside the container; compose publishes it on the host's 127.0.0.1

# compose publishes ports from .env (it cannot read the JSON); catch a mismatch instead of
# starting a server nobody can reach.
for pair in "campaign:$CAMPAIGN_PORT:${PUBLISHED_CAMPAIGN_PORT:-}" "multiplayer:$MULTIPLAYER_PORT:${PUBLISHED_MULTIPLAYER_PORT:-}"; do
  IFS=: read -r which want published <<<"$pair"
  [ -z "$published" ] || [ "$published" = "$want" ] ||
    die "the $which port is $want but compose publishes $published. Set $(echo "$which" | tr a-z A-Z)_PORT=$want in .env."
done

[ "$CAMPAIGN_PORT" != "$MULTIPLAYER_PORT" ] || die "campaign and multiplayer ports must differ"

# --- Mission (from the shared file) ---
row="$(jq -r --argjson id "$MISSION" '.campaign.missions[] | select(.id == $id) | "\(.game)|\(.name)"' "$CONFIG_FILE")"
if [ -z "$row" ]; then
  echo "Unknown MISSION '$MISSION'. Valid mission numbers:" >&2
  jq -r '.campaign.missions[] | "  \(.id)  \(.name) (\(if .game == "odst" then "ODST" else "Halo 3" end))"' "$CONFIG_FILE" >&2
  exit 1
fi
MISSION_GAME="${row%%|*}"
MISSION_NAME="${row#*|}"

DEDICATED=(project-reclaimer dedicated)
cd "$SERVER_DIR"

# --- One-time game file setup from the MCC install (re-running init keeps existing settings) ---
init_from_mcc() {  # $1 = --maps value
  [ -d "$MCC_DIR" ] && [ -n "$(ls -A "$MCC_DIR" 2>/dev/null)" ] ||
    die "game files are missing and $MCC_DIR is empty. Mount your MCC install there (set MCC_DIR in .env)."
  log "dedicated init --maps $1 (copying from MCC; this can take a while)"
  "${DEDICATED[@]}" init "$SERVER_DIR" --from "$MCC_DIR" --maps "$1"
}

if [ "$MISSION_GAME" = odst ]; then
  marker=game/halo3odst/maps/shared.map; campaign_maps=odst
else
  marker=game/halo3/halo3.dll; campaign_maps=campaign
fi
[ -f "$marker" ] || init_from_mcc "$campaign_maps"

missing=()
while read -r stem; do
  [ -f "game/halo3/maps/$stem.map" ] || missing+=("$stem")
done < <(cfg '.multiplayer.maps[].file')
if [ "${#missing[@]}" -gt 0 ]; then
  init_from_mcc "$(IFS=,; echo "${missing[*]}")"
fi

# --- RCON password: RCON_PASSWORD env, else one generated on first run and kept ---
pwfile=rcon-password.txt
if [ -n "${RCON_PASSWORD:-}" ]; then
  rcon_password="$RCON_PASSWORD"
else
  [ -s "$pwfile" ] || { LC_ALL=C tr -dc 'A-HJ-NP-Za-km-z2-9' </dev/urandom | head -c 24 >"$pwfile" || true; }
  rcon_password="$(tr -d '[:space:]' <"$pwfile")"
fi
[ "${#rcon_password}" -ge 8 ] || die "RCON password must be at least 8 characters"

# --- Multiplayer playlist: one round per game so a new vote follows every round ---
mkdir -p playlists
jq --arg name "$MULTIPLAYER_NAME" --argjson votes "$VOTE_SECONDS" '.multiplayer as $m | {
    version: 2, name: $name, vote_seconds: $votes,
    games: [ $m.maps[] as $map | $m.modes[] as $mode
             | {map: $map.name, game: $mode.game, name: $mode.name, options: {"rounds.limit": $m.rounds_limit}} ]
  }' "$CONFIG_FILE" >playlists/lan-multiplayer.playlist.json

# --- dedicated.toml: both servers in one file, one process ---
skulls="$(cfg '[.campaign.skulls[]] | add')"
if [ "$MISSION_GAME" = odst ]; then section=odst; characters=''; else section=campaign; characters="custom_characters = $(cfg .campaign.custom_characters)"; fi

cat >dedicated.toml <<EOF
# Generated by entrypoint.sh on every start from reclaimer.config.json; edit that, not this.
game = "game"
content = "content"
upnp = $(cfg .server.upnp)

# Remote console on TCP at each game port.
[rcon]
password = $(tstr "$rcon_password")
address = $(tstr "$RCON_ADDRESS")

# Campaign co-op: $MISSION_NAME ($MISSION)
[[server]]
name = $(tstr "$CAMPAIGN_NAME")
port = $CAMPAIGN_PORT
max_players = $(cfg .server.max_players)
hidden = $(cfg .server.hidden)
friendly_fire = $(cfg .server.friendly_fire)
voice = $(cfg .server.voice)

[server.$section]
mission = $MISSION
insertion = $(cfg .campaign.insertion)
difficulty = "$(cfg .campaign.difficulty)"
$characters

[server.$section.modifiers]
health_per_player_percent = $(cfg .campaign.health_per_player_percent)
damage_per_player_percent = $(cfg .campaign.damage_per_player_percent)
sprint = $(cfg .campaign.sprint)
skulls = $skulls

# Multiplayer playlist with a vote between games
[[server]]
name = $(tstr "$MULTIPLAYER_NAME")
port = $MULTIPLAYER_PORT
max_players = $(cfg .server.max_players)
hidden = $(cfg .server.hidden)
friendly_fire = $(cfg .server.friendly_fire)
voice = $(cfg .server.voice)
playlist = "playlists/lan-multiplayer.playlist.json"
EOF

log "$(cat "$VERSION_FILE"): '$CAMPAIGN_NAME' ($MISSION_NAME) on UDP $CAMPAIGN_PORT, '$MULTIPLAYER_NAME' on UDP $MULTIPLAYER_PORT"
log "Players: Direct Connect to <this host's LAN IP>:$CAMPAIGN_PORT or :$MULTIPLAYER_PORT"

"${DEDICATED[@]}" --config dedicated.toml check ||
  die "dedicated check failed; see the lines it names above"
exec "${DEDICATED[@]}" --config dedicated.toml
